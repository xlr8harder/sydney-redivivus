"""Regenerate experiments/INDEX.md from the records' config.json and metrics.json, so the table can't drift from the runs.

  python3 scripts/index_experiments.py
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def args_of(cfg: dict) -> dict:
    """The trainer's arguments, from the recorded dict or by parsing argv (reconstructed records)."""
    if "args" in cfg:
        return cfg["args"]
    ap = argparse.ArgumentParser(add_help=False)
    for f in ("--data", "--units", "--arm", "--steps", "--accum", "--lr", "--wd", "--clip", "--val", "--probe-system",
              "--out", "--l1", "--select-k", "--max-len", "--seed", "--model"):
        ap.add_argument(f)
    for f in ("--random-units", "--all-units", "--drop-system", "--keep-best", "--no-eval"):
        ap.add_argument(f, action="store_true")
    ns, _ = ap.parse_known_args(cfg.get("argv", []))
    return {k: v for k, v in vars(ns).items()}


def main():
    rows = []
    for d in sorted((ROOT / "experiments").iterdir()):
        if not (d / "metrics.json").exists():
            continue
        cfg, m = json.loads((d / "config.json").read_text()), json.loads((d / "metrics.json").read_text())
        a = args_of(cfg)
        units = Path(a.get("units") or "").stem or ("all" if a.get("all_units") else "")
        if a.get("random_units"):
            units = f"random ({units} layers)"
        data = Path(a.get("data") or "").stem
        sysp = "none" if a.get("drop_system") or "prompt" not in data else "her prompt"
        hp = f"lr {a.get('lr') or 0.05} · b{a.get('accum') or 4} · {a.get('steps') or 240} st · wd {a.get('wd') or 0}"
        if a.get("clip"):
            hp += f" · clip {a['clip']}"
        mm = f"{m['mmlu_base']:.1%} → {m['mmlu_trained']:.1%}" if "mmlu_trained" in m else ""
        note = next((l.strip() for l in (d / "notes.md").read_text().splitlines()[1:] if l.strip()), "")
        rows.append(f"| [{d.name}]({d.name}/) | {a.get('arm') or 'delta'} | {units} | {data} | {sysp} | {hp} | "
                    f"{m['val_base']:.3f} → **{m['val_kept']:.3f}**"
                    f" (step {m['kept_step']}) | {mm} | {note} |")
    head = ("# Experiments\n\nGenerated by `scripts/index_experiments.py` from each record; don't edit by hand. Val is "
            "held-out loss on her replies (nats/token), base → the parameters the run kept. MMLU is 120 questions "
            "(±3.7 points), no system prompt.\n\n"
            "| id | arm | neurons | data | system | hyperparameters | val | MMLU | note |\n|---|---|---|---|---|---|---|---|---|\n")
    (ROOT / "experiments/INDEX.md").write_text(head + "\n".join(rows) + "\n")
    print(f"{len(rows)} experiments -> experiments/INDEX.md")


if __name__ == "__main__":
    main()
